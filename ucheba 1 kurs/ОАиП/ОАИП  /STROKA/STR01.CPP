// удалить из строки символов подстроку заключенную в [ ]

#include<stdio.h>
#include<conio.h>
#define k 10
void main(void)
{ char ss[k];
  int i,j,t;
  clrscr();
  printf("введите строку символов  ");
  fflush(stdin);    // чистка входного буффера
  gets(ss);
  printf("\nИсходная строка символов :  %s",ss);
  j=-1;                      //позиция открывающей скобки  '[' в строке
  for(i=0;ss[i]!='\0';i++)   //цикл прохода по строке до ее конца
  { if (ss[i]=='[')          // скобка найдена
    { j=i;
      while(ss[++j]!=']' && ss[j]!='[' && ss[j]!='\0');
      if (ss[j]=='[') i=j-1; // позиция вложенной скобки  [ (теперь основной)
			     // во внешнем цикле по i увеличится значние i
      else if(ss[j]==']')    // позиция закрывающей скобки
	   { for(int n=i;;n++)
	     { ss[n]=ss[n+j-i+1];  // сжатие строки (удаление подстроки)
	       if (ss[n]=='\0') break;
	     }
	     i--;         // после сжатия надо проверить первый из символов
			  // сдвинутых на [...] не является ли он сам [
	   }
    }
  }
  printf("\nCжатая строка символов :  %s",ss);
  getch();
}
