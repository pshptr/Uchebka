  // ввести массив строк. для каждой строки во всех
  // последующих строках найти слова совпадающие со словом
  // из выбранной строки и удалить их (в исходной строке
  // слова не удалять)
  #include<stdio.h>
  #include<conio.h>
  # define kk 3
  # define nn 20
  int sravn(char *,char *);
  void udal(char *);

  void main(void)
  { char st[kk][nn];
    int i,i1,j,j1;
    clrscr();
    fflush(stdin);
    for(i=0;i<kk;i++)
    { printf("\nВводите %d символьную строку :",i+1);
      gets(st[i]);
    }
    printf("\nСтроки до преобразования");
    for (i=0;i<kk;i++) printf("\n  %s",st[i]);
    for(i=0;i<kk-1;i++)
    { for(j=0;st[i][j]!='\0';j++)
      if (j==0 || st[i][j-1]==' ')        // выбрано исходное слово
      { for(i1=i+1;i1<kk;i1++)
        for(j1=0;st[i1][j1]!='\0';j1++)
        if (j1==0 || st[i1][j1-1]==' ')   // выбрано слово для сравнения
        if (!sravn(&st[i][j],&st[i1][j1]))  // слова совпали
    udal(&st[i1][j1]);
      }
    }

    printf("\nСтроки после преобразования");
    for (i=0;i<kk;i++) printf("\n  %s",st[i]);
    getch();
  }

  // функция сравнения двух слов
  int sravn(char *s1,char *s2)
  { while(*s1 && *s2 && *s1!=' ' && *s2!=' ')     // истина пока не достигнут конец ('\0') строки s1
    if (*s1-*s2) return *s1-*s2;  // >0 если ASCII-код  *s1 > *s2
          // иначе <0
    else                          // при совпадении символов переход
    { s1++;                       // к анализу следующей пары символов
      s2++;
    }
    return 0;                     // строки полностью совпали
  }

  // функция удаления из строки слова
  void udal(char *s)
  { int jj=0,j=0;
    while(*(s+jj)!='\0' && *(s+jj)!=' ')
    jj++;                        //подсчет длины слова
    if (*(s+jj)!='\0') jj++;     //выход на первую букву следующего слова
    while(*(s+jj)!='\0')
      *(s+j++)=*(s+jj++);       //сдвиг строки влево на размер слова
    *(s+j)='\0';                 //усечение строки
  }
